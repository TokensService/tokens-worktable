#!/usr/bin/env bash
# Prepare one deployment contract: pre-pull the image, then render templates.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
IMAGE_NAME="${IMAGE_NAME:-${DEPLOY_IMAGE:-myapp}}"
ARCH_NAME="${ARCH_NAME:-default}"
PIPELINE_NAME="${PIPELINE_NAME:-xds-${ARCH_NAME}}"
RUN_DIR="${RUN_DIR:-/tmp/${PIPELINE_NAME}-$(date +%Y%m%d_%H%M%S)}"
RENDER_DIR="${RENDER_DIR:-${RUN_DIR}/rendered}"
DEPLOY_IMAGE="${DEPLOY_IMAGE:-$IMAGE_NAME}"
NAMESPACE="${NAMESPACE:-xds-${ARCH_NAME}-${IMAGE_TAG:-local}}"
RELEASE_NAME="${RELEASE_NAME:-$NAMESPACE}"
CHART_DIR="${CHART_DIR:-${RENDER_DIR}/xds-cluster}"
VALUES_FILE="${VALUES_FILE:-${RENDER_DIR}/values.rendered.yaml}"
ARCH_REQUEST_FILE="${ARCH_REQUEST_FILE:-${RENDER_DIR}/architecture.request.json}"
RESOURCE_MANIFEST="${RESOURCE_MANIFEST:-${RENDER_DIR}/resources.rendered.json}"
NODE_LABELS_FILE="${NODE_LABELS_FILE:-${RENDER_DIR}/node-labels.json}"
XDS_URL="${XDS_URL:-http://127.0.0.1:30079/xds/v1}"
HELM_BIN="${HELM_BIN:-helm}"
KUBECTL_BIN="${KUBECTL_BIN:-kubectl}"
HELM_TIMEOUT="${HELM_TIMEOUT:-10m}"
XDS_READY_TIMEOUT_SECONDS="${XDS_READY_TIMEOUT_SECONDS:-1800}"
XDS_READY_POLL_SECONDS="${XDS_READY_POLL_SECONDS:-5}"
HEAD_LOG_ROOT="${HEAD_LOG_ROOT:-./logs}"
POLL_INTERVAL_SECONDS="${POLL_INTERVAL_SECONDS:-5}"
PIPELINE_ENV_FILE="${PIPELINE_ENV_FILE:-${RUN_DIR}/pipeline.env}"

export IMAGE_NAME ARCH_NAME PIPELINE_NAME RUN_DIR RENDER_DIR DEPLOY_IMAGE \
  NAMESPACE RELEASE_NAME CHART_DIR VALUES_FILE ARCH_REQUEST_FILE RESOURCE_MANIFEST \
  NODE_LABELS_FILE XDS_URL HELM_BIN KUBECTL_BIN HELM_TIMEOUT \
  XDS_READY_TIMEOUT_SECONDS XDS_READY_POLL_SECONDS HEAD_LOG_ROOT \
  POLL_INTERVAL_SECONDS PIPELINE_ENV_FILE

write_pipeline_env() {
  local variable
  mkdir -p "$(dirname "$PIPELINE_ENV_FILE")"
  (
    umask 077
    {
      printf '# Generated by pull_render_config.sh. Load before the next pipeline stage.\n'
      for variable in \
        IMAGE_NAME DEPLOY_IMAGE ARCH_NAME PIPELINE_NAME RUN_DIR RENDER_DIR \
        CHART_DIR VALUES_FILE ARCH_REQUEST_FILE RESOURCE_MANIFEST NODE_LABELS_FILE \
        NAMESPACE RELEASE_NAME XDS_URL HELM_BIN KUBECTL_BIN HELM_TIMEOUT \
        XDS_READY_TIMEOUT_SECONDS XDS_READY_POLL_SECONDS HEAD_LOG_ROOT \
        POLL_INTERVAL_SECONDS; do
        printf 'export %s=%q\n' "$variable" "${!variable}"
      done
    } >"$PIPELINE_ENV_FILE"
  )
}

echo "[pipeline] image=$IMAGE_NAME arch=$ARCH_NAME run_dir=$RUN_DIR render_dir=$RENDER_DIR"
bash "$SCRIPT_DIR/pull-image.sh"
bash "$SCRIPT_DIR/render-config.sh"
write_pipeline_env
printf 'PIPELINE_ENV_FILE=%s\n' "$PIPELINE_ENV_FILE"
